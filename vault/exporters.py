# -*- coding: utf-8 -*-
"""Export routines for encrypted archives, .env configuration, and backups (Improvements #24, #28)."""
from __future__ import annotations

import csv
import gzip
from pathlib import Path
from typing import Any, Dict, List, Optional

from vault.constants import EXPORT_MAGIC_GZ, EXPORT_MAGIC_V3
from vault.models import entry_custom_fields, entry_secret, entry_totp, entry_type
from vault.storage import secure_write


def to_env_name(name: str) -> str:
    """Derive standard uppercase environment variable name."""
    s = name.strip()
    clean = "".join(c if (c.isalnum() or c == "_") else "_" for c in s)
    while "__" in clean:
        clean = clean.replace("__", "_")
    clean = clean.strip("_").upper()
    if not clean:
        return "SECRET"
    if clean[0].isdigit():
        clean = "_" + clean
    return clean


def export_vault(
    session: Any,
    vault: Dict[str, Any],
    output_path: Optional[Path] = None,
    compress: bool = False,
) -> Path:
    """Export encrypted vault archive using active master session key, with optional gzip compression."""
    from vault.crypto import pack_container

    suffix = ".pvex.gz" if compress else ".pvex"
    out = output_path or Path.cwd() / f"vault-export{suffix}"
    packed = pack_container(session, vault)
    if compress:
        compressed = gzip.compress(packed, compresslevel=9)
        secure_write(out, EXPORT_MAGIC_GZ + compressed)
    else:
        secure_write(out, EXPORT_MAGIC_V3 + packed)
    return out


def export_dotenv(
    vault: Dict[str, Any],
    output_path: Path,
    keys: Optional[List[str]] = None,
) -> int:
    """Export selected credentials into a .env formatted file (Improvement #24)."""
    from vault.models import entry_secret

    lines: List[str] = [
        "# Generated by Secure Password Vault",
        f"# Total entries: {len(vault)}",
        "",
    ]
    count = 0
    targets = keys if keys is not None else list(vault.keys())

    for target in targets:
        if target not in vault:
            continue
        entry = vault[target]
        env_var = entry.get("env") or to_env_name(target)
        val = entry_secret(entry)
        escaped_val = val.replace('"', '\\"')
        lines.append(f'{env_var}="{escaped_val}"')
        count += 1

    content = "\n".join(lines) + "\n"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = output_path.with_suffix(output_path.suffix + ".tmp")
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(content)
        f.flush()
    tmp_path.replace(output_path)
    return count


def export_encrypted_json(
    vault: Dict[str, Any],
    output_path: Path,
    passphrase: str,
) -> Path:
    """Export credentials to an authenticated AES-256-GCM encrypted JSON envelope."""
    from vault.crypto import pack_encrypted_json

    envelope = pack_encrypted_json(vault, passphrase)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = output_path.with_suffix(output_path.suffix + ".tmp")
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(envelope)
        f.flush()
    tmp_path.replace(output_path)
    return output_path


def export_csv(
    vault: Dict[str, Any],
    output_path: Path,
    delimiter: str = ",",
    fields: Optional[List[str]] = None,
) -> int:
    """Export credentials to customizable CSV format."""
    chosen_fields = fields or ["name", "type", "username", "password", "url", "notes", "totp", "tags"]
    output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = output_path.with_suffix(output_path.suffix + ".tmp")

    count = 0
    with open(tmp_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, delimiter=delimiter)
        writer.writerow(chosen_fields)
        for name, entry in sorted(vault.items()):
            row = []
            for field in chosen_fields:
                if field == "name":
                    row.append(name)
                elif field == "type":
                    row.append(entry_type(entry))
                elif field == "username":
                    row.append(entry.get("username", ""))
                elif field == "password":
                    row.append(entry_secret(entry))
                elif field == "url":
                    row.append(entry.get("url", ""))
                elif field == "notes":
                    row.append(entry.get("notes", ""))
                elif field == "totp":
                    row.append(entry_totp(entry))
                elif field == "tags":
                    row.append(", ".join(entry.get("tags", [])))
                else:
                    custom = entry_custom_fields(entry)
                    row.append(custom.get(field, ""))
            writer.writerow(row)
            count += 1
        f.flush()
    tmp_path.replace(output_path)
    return count

